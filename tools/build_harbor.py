"""
Shiomi, the harbour town by the sea (chapter 4), from the painted ground (art/sheets/ground_harbor_draft.webp, 42 x 28 tiles).

Writes:
  public/assets/map_harbor.png      the ground picture scaled to the grid
  public/assets/bx_<name>.png       the town buildings (hm_exterior_harbor.webp)
  src/content/harbor.gen.ts         collision / terrain grid

The grid was read off the picture by hand: everything is blocked (forest, cliffs, rocks, sea) unless carved out.
Legend: . walkable  : path  " tall grass (wild Kotodama)  p pavement  b pier / stepping stones  H stairs  T blocked

Run: python3 tools/build_harbor.py
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from build_rooms import piece, sheet  # noqa: E402
from extract_sheets import OUT, ROOT, resize_px  # noqa: E402

W, H, T = 42, 28, 32
g = [['T'] * W for _ in range(H)]


def rect(ch, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


# --- north-west: the station on the hill and the lanes down the slope
rect('.', 5, 1, 9, 1)           # platform (the station building stands on it)
rect(':', 10, 1, 11, 3)         # from the platform down the hill
rect('H', 11, 3, 11, 3)
rect(':', 10, 4, 13, 7)
rect(':', 12, 7, 22, 7)         # the lane across the slope
rect('H', 11, 8, 11, 9)
rect(':', 9, 9, 11, 10)
rect('H', 10, 11, 10, 11)
rect(':', 7, 12, 12, 12)
rect('H', 6, 12, 6, 13)         # stairs down to the beach
rect('.', 5, 5, 9, 6)           # little meadow above the dunes
rect('H', 7, 7, 7, 7)
rect('"', 0, 7, 8, 11)          # tall grass in the dunes (wild Kotodama)
# --- the beach
rect('.', 0, 13, 12, 15)
rect('.', 1, 16, 8, 17)
# --- upper plots on the slope
rect('.', 15, 4, 19, 5)         # garden plot (lemon trees)
rect('H', 16, 6, 16, 6)
rect(':', 19, 1, 21, 6)         # path up into the forest edge
rect(':', 21, 3, 23, 8)         # down to the main stairs
rect('.', 24, 4, 29, 5)         # Gen-san's house plot
rect('H', 25, 6, 26, 6)
rect(':', 24, 7, 31, 8)
# --- the main stone stairs and the harbour square
rect('H', 22, 8, 22, 9)
rect('p', 20, 10, 23, 15)       # the paved street down to the harbour
rect('p', 12, 13, 31, 15)       # the harbour square along the quay
rect('.', 14, 10, 19, 12)       # diner plot
rect('H', 14, 9, 14, 9)
rect('.', 24, 10, 30, 12)       # inn plot
rect(':', 30, 9, 31, 12)
rect('H', 30, 11, 31, 12)
rect('.', 25, 13, 28, 14)       # harbour office plot
# --- piers and the breakwater
rect('b', 15, 16, 16, 20)       # wooden pier (west)
rect('p', 22, 16, 23, 19)       # breakwater
rect('p', 22, 20, 22, 22)
rect('p', 23, 18, 25, 18)       # the landing beside it
rect('H', 28, 16, 28, 16)
rect('b', 28, 17, 29, 21)       # wooden pier (east)
# --- east: the cliff path up to the lighthouse, tall grass on the cliff top
rect(':', 31, 8, 35, 9)
rect('H', 34, 10, 35, 10)
rect(':', 32, 3, 34, 7)
rect(':', 34, 2, 35, 3)
rect('.', 36, 2, 37, 4)         # in front of the lighthouse (the tower stands on the rest of the plot)
rect('.', 33, 11, 36, 12)
rect('"', 37, 9, 40, 12)        # tall grass on the cliff top (wild Kotodama)
# --- the stepping stones to the little island
rect('b', 31, 15, 32, 16)
rect('b', 32, 17, 33, 17)
rect('b', 33, 18, 34, 18)
rect('b', 34, 19, 35, 19)
rect('b', 35, 20, 36, 20)
rect('.', 36, 19, 40, 22)       # the island (pines, a tiny shrine)
rect('T', 37, 19, 38, 20)       # the big pines

# buildings: name -> (piece index in hm_exterior_harbor.webp, width px, footprint x, y, w, h)
BUILDINGS = {
    'lighthouse': (0, 124, 38, 3, 3, 2),
    'diner': (1, 200, 14, 11, 6, 2),
    'harbor_office': (2, 120, 25, 13, 4, 2),
    'seaside_inn': (3, 210, 24, 11, 7, 2),
    'townhouse': (4, 100, 25, 4, 3, 2),
    'shiomi_station': (5, 150, 5, 1, 5, 2),
}


def main():
    sheet('exterior_harbor')
    for key, (idx, width, x, y, w, h) in BUILDINGS.items():
        img = piece('exterior_harbor', idx, scale=1)
        resize_px(img, round(img.height * width / img.width)).save(os.path.join(OUT, f'bx_{key}.png'))
        rect('T', x, y, x + w - 1, y + h - 1)
    rows = [''.join(r) for r in g]
    src = Image.open(os.path.join(ROOT, 'art', 'sheets', 'ground_harbor_draft.webp')).convert('RGB')
    src.resize((W * T, H * T), Image.LANCZOS).save(os.path.join(OUT, 'map_harbor.png'))
    ts = '/* generated by tools/build_harbor.py — do not edit */\nexport const HARBOR_GEN: string[] = ' + json.dumps(rows, indent=2) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'harbor.gen.ts'), 'w').write(ts)
    print('\n'.join(f'{i:2d} {r}' for i, r in enumerate(rows)))


if __name__ == '__main__':
    main()
