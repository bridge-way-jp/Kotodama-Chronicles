"""
Yukimi, the snowy mountain village (chapter 3), from the painted ground (art/sheets/ground_mountain_draft.webp, 42 x 28 tiles).

Writes:
  public/assets/map_mountain.png    the ground picture scaled to the grid
  public/assets/bx_<name>.png       the village buildings (hm_exterior_mountain.webp)
  src/content/mountain.gen.ts       collision / terrain grid

The grid was read off the picture by hand: everything is blocked (forest, cliffs, terraces) unless carved out.
Legend: . walkable  : path  " tall grass (wild Kotodama)  ~ water / ice  b bridge  H stairs  T blocked

Run: python3 tools/build_mountain.py
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from build_rooms import piece, sheet  # noqa: E402
from extract_sheets import OUT, ROOT, resize_px  # noqa: E402

W, H, T = 42, 28, 32
g = [['T'] * W for _ in range(H)]


def rect(ch, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


# --- north: temple on the hill, path along the rice terraces
rect('.', 18, 1, 23, 3)         # temple plot (the hall covers most of it)
rect('H', 20, 4, 21, 6)         # temple stairs
rect(':', 14, 6, 21, 7)         # path below the temple stairs
rect(':', 16, 8, 19, 8)         # down to the bridge
rect(':', 12, 2, 13, 3)         # path at the top of the terraces
rect(':', 13, 4, 14, 4)
rect('H', 13, 5, 14, 5)
# --- the arched stone bridge (north-west to south-east)
rect('b', 17, 9, 18, 9)
rect('b', 18, 10, 20, 10)
rect('b', 19, 11, 21, 11)
rect('b', 20, 12, 21, 12)
# --- west: tall grass, stairs, the path down to the station
rect('"', 2, 11, 7, 13)         # frosty bamboo grass (wild Kotodama)
rect(':', 10, 10, 11, 10)       # viewpoint by the lantern
rect('H', 10, 11, 10, 11)
rect(':', 8, 12, 10, 13)
rect(':', 7, 13, 9, 15)
rect('.', 3, 14, 6, 14)
rect('H', 4, 15, 5, 15)         # small stairs down from the grass
rect('H', 7, 16, 7, 16)
rect(':', 7, 17, 9, 18)
rect('.', 3, 16, 8, 19)         # snow field north of the railway
rect(':', 9, 19, 16, 20)        # path from the station to the square
rect(':', 16, 18, 19, 19)
rect(':', 6, 20, 10, 21)        # station platform
rect('H', 11, 21, 12, 21)       # stairs to the festival plot
rect('.', 13, 21, 18, 23)       # festival plot (snow lanterns)
# --- the square and the main road
rect(':', 20, 13, 22, 24)       # main road from the bridge to the south stairs
rect(':', 20, 17, 28, 19)       # village square
rect('T', 21, 18, 22, 19)       # the big tree with lanterns
rect(':', 22, 12, 29, 13)       # south-bank path east
rect(':', 28, 13, 31, 17)
rect(':', 29, 11, 30, 12)
rect(':', 30, 10, 34, 10)
rect('H', 33, 11, 33, 11)       # stairs down to the guesthouse
rect(':', 33, 12, 33, 13)
rect('H', 21, 25, 22, 26)       # stairs down to the mountain trail (closed for now)
# --- building plots
rect('.', 17, 14, 20, 16)       # kamakura plot
rect('.', 24, 14, 28, 16)       # small farmhouse plot
rect('.', 32, 14, 37, 18)       # guesthouse plot
rect('.', 23, 20, 29, 23)       # clinic plot
# --- east: frozen pond and tall grass
rect('.', 35, 6, 40, 9)
rect('~', 36, 7, 39, 9)         # the frozen pond
rect(':', 34, 9, 35, 10)
rect('.', 35, 10, 36, 11)
rect('"', 37, 10, 40, 13)

# buildings: name -> (piece index in hm_exterior_mountain.webp, width px, footprint x, y, w, h)
BUILDINGS = {
    'guesthouse': (0, 200, 32, 15, 6, 2),
    'gassho': (1, 150, 24, 14, 5, 2),
    'clinic': (2, 150, 25, 20, 5, 2),
    'temple': (3, 192, 18, 2, 6, 2),
    'yukimi_station': (4, 136, 1, 19, 4, 2),
    'kamakura': (5, 100, 17, 15, 3, 1),
}


def main():
    sheet('exterior_mountain')
    for key, (idx, width, x, y, w, h) in BUILDINGS.items():
        img = piece('exterior_mountain', idx, scale=1)
        resize_px(img, round(img.height * width / img.width)).save(os.path.join(OUT, f'bx_{key}.png'))
        rect('T', x, y, x + w - 1, y + h - 1)
    rect('T', 18, 1, 23, 1)  # behind the temple hall
    rows = [''.join(r) for r in g]
    src = Image.open(os.path.join(ROOT, 'art', 'sheets', 'ground_mountain_draft.webp')).convert('RGB')
    src.resize((W * T, H * T), Image.LANCZOS).save(os.path.join(OUT, 'map_mountain.png'))
    ts = '/* generated by tools/build_mountain.py — do not edit */\nexport const MOUNTAIN_GEN: string[] = ' + json.dumps(rows, indent=2) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'mountain.gen.ts'), 'w').write(ts)
    print('\n'.join(f'{i:2d} {r}' for i, r in enumerate(rows)))


if __name__ == '__main__':
    main()
