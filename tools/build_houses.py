"""
Swap the repeated buildings of the towns for the new house variants (art/sheets/haeuser_<set>.webp, 12 buildings each).

Each target object keeps its footprint and gets a new sprite scaled to the pixel width of the one it replaces
(public/assets/bx_n_<object>.png). Writes src/content/houses.gen.ts (object id -> sprite) used by maps.ts.

Pieces are numbered in reading order (rows top to bottom, left to right). The sets:
  kyoto:   0-3 machiya (blue / red / green / purple noren), 4 tea house with umbrella, 5 house with garden gate, 6 two-storey machiya,
           7 pink wagashi shop, 8 dango sweet shop, 9 pickle shop with barrels, 10 kimono shop, 11 inn with gate
  osaka:   0 takoyaki, 1 okonomiyaki, 2 fugu, 3-5 izakaya, 6 cinema, 7 arcade, 8 red department store, 9 green department store, 10 shrine shop, 11 tower
  tokyo:   0 blue glass, 1 grey office, 2 red brick, 3 green terraces, 4 black glass, 5 teal round, 6 corner konbini, 7 ramen, 8 cafe, 9 game centre, 10 bookshop, 11 pharmacy
  doerfer: 0-1 thatched farmhouse, 2 tiled farmhouse, 3-5 harbour houses, 6-8 snow gassho, 9 village shop, 10 wayside shrine house, 11 storehouse

Run: python3 tools/build_houses.py
"""
