# the one Asakusa souvenir shop borrows a Kyoto look (a wooden sweets shop with lanterns)
CROSS = {'t_asakusa_h1': ('kyoto', 8)}


def pieces(sheet):
    a = load(f'haeuser_{sheet}.webp')
    fg = ~magenta_mask(a)
    boxes = [b for r in rows_of(components(fg, min_area=6000, dilate=2), tol=120) for b in r]
    out = []
    for x0, y0, x1, y1 in boxes:
        out.append(defringe(trim(to_rgba(a[y0:y1, x0:x1], fg[y0:y1, x0:x1]))))
    return out


def old_sprites():
    text = ''
    for f in ('kyoto.gen.ts', 'osaka.gen.ts', 'tokyo.gen.ts', 'maps.ts'):
        text += open(os.path.join(ROOT, 'src', 'content', f)).read()
    found = {}
    for m in re.finditer(r'''["']?id["']?:\s*["']([a-z0-9_]+)["'],\s*["']?sprite["']?:\s*["']([a-zA-Z0-9_]+)["']''', text):
        found[m.group(1)] = m.group(2)
    for tb in 'tb':
        for i in range(6):
            found[f'k_shop_{tb}{i}'] = f'bx_k_nishiki_shop_{tb}{i}'  # built in a loop in maps.ts
    return found


def main():
    old = old_sprites()
    sets = {k: pieces(k) for k in SWAPS}
    for k, v in sets.items():
        print(k, len(v), 'pieces')
        assert len(v) == 12, k
    out = {}
    jobs = [(oid, s, i) for s, d in SWAPS.items() for oid, i in d.items()] + [(oid, s, i) for oid, (s, i) in CROSS.items()]
    for oid, s, i in jobs:
        spr = old[oid]
        width = Image.open(os.path.join(OUT, spr + '.png')).width
        p = sets[s][i]
        h = max(8, round(p.height * width / p.width))
        resize_px(p, h).save(os.path.join(OUT, f'bx_n_{oid}.png'))
        out[oid] = f'bx_n_{oid}'
    ts = '/* generated by tools/build_houses.py — do not edit */\n'
    ts += '/** map object id -> the sprite of its new house variant */\nexport const HOUSE_SWAPS: Record<string, string> = ' + json.dumps(out, indent=2) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'houses.gen.ts'), 'w').write(ts)
    print(len(out), 'swaps')


if __name__ == '__main__':
    main()
