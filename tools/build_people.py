"""
Cuts the walk-cycle sheets (laufen_NN.png: two people, 3 rows down / left / up x 4 frames each) and the portrait sheets
(portraits_N.png: one row of neutral / happy / surprised / worried per person) made from
tools/make_people_seasons_zip.py, in the order of that tool's lists.

Writes public/assets/npc_<who>_<dir>_<frame>.png (right = mirrored left), npc_<who>_<dir>.png (the standing frame),
portrait_<who>_<expression>.png, and src/content/people.gen.ts (who walks, and the own look of the people who
borrowed someone else's until now).

  python3 tools/build_people.py <dir with laufen_*.png and portraits_*.png>
"""
import glob
import json
import os
import sys

import numpy as np
from PIL import Image, ImageOps
from scipy import ndimage

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_sheets import OUT, magenta_mask, resize_px, to_rgba, trim  # noqa: E402
from make_people_seasons_zip import MAIN, NEW, PORTRAIT_ONLY  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEIGHT = 46  # the walk frames of the heroine
EXPR = ['neutral', 'happy', 'surprised', 'worried']


def splits(profile, n):
    """cut points: the emptiest line near each equal division"""
    L = len(profile)
    cuts = [0]
    for i in range(1, n):
        t = int(L * i / n)
        lo, hi = max(0, t - L // (3 * n)), min(L, t + L // (3 * n))
        cuts.append(lo + int(np.argmin(profile[lo:hi])))
    return cuts + [L]


def grid(a, rows, cols):
    """the cells of a rows x cols sheet, as boxes (x0, y0, x1, y1)"""
    fg = ndimage.binary_opening(~magenta_mask(a))
    ys = splits(fg.sum(1), rows)
    out = []
    for r in range(rows):
        band = fg[ys[r]:ys[r + 1]]
        xs = splits(band.sum(0), cols)
        out.append([(xs[c], ys[r], xs[c + 1], ys[r + 1]) for c in range(cols)])
    return fg, out


def sprite(a, fg, box):
    x0, y0, x1, y1 = box
    keep = fg[y0:y1, x0:x1]
    lab, n = ndimage.label(keep)
    if n > 1:  # only the biggest piece (no slivers of a neighbour)
        sizes = ndimage.sum(keep, lab, range(1, n + 1))
        keep = lab == (int(np.argmax(sizes)) + 1)
    return trim(to_rgba(a[y0:y1, x0:x1], keep))


def walk_sheets(src):
    people = [p for p, _ in MAIN] + [p for p, _ in NEW]
    walkers = []
    for n, f in enumerate(sorted(glob.glob(os.path.join(src, 'laufen_*.png')))):
        a = np.array(Image.open(f).convert('RGB')).astype(int)
        fg, rows = grid(a, 3, 8)
        pair = people[n * 2:n * 2 + 2]
        for side, who in enumerate(pair):
            frames = {d: [sprite(a, fg, b) for b in rows[r][side * 4:side * 4 + 4]] for r, d in enumerate(('down', 'left', 'up'))}
            # one scale for all frames of a person, so the steps do not change their size
            scale = HEIGHT / max(im.height for im in frames['down'])
            for d, ims in list(frames.items()) + [('right', [ImageOps.mirror(im) for im in frames['left']])]:
                for k, im in enumerate(ims):
                    out = resize_px(im, max(1, round(im.height * scale)))
                    out.save(os.path.join(OUT, f'npc_{who}_{d}_{k}.png'))
                    if k == 0:
                        out.save(os.path.join(OUT, f'npc_{who}_{d}.png'))
            walkers.append(who)
        print(os.path.basename(f), pair)
    return walkers


def portrait_sheets(src):
    todo = [p for p, _ in NEW + PORTRAIT_ONLY]
    done = []
    for n, f in enumerate(sorted(glob.glob(os.path.join(src, 'portraits_*.png')))):
        group = todo[n * 4:n * 4 + 4]
        a = np.array(Image.open(f).convert('RGB')).astype(int)
        fg, rows = grid(a, len(group), 4)
        for who, row in zip(group, rows):
            for k, b in enumerate(row[:4]):
                resize_px(sprite(a, fg, b), 104).save(os.path.join(OUT, f'portrait_{who}_{EXPR[k]}.png'))
            done.append(who)
        print(os.path.basename(f), group)
    return done


def main():
    src = sys.argv[1]
    walkers = walk_sheets(src)
    portraits = portrait_sheets(src)
    looks = {who: {'sprite': f'npc_{who}', 'portrait': f'portrait_{who}'} for who, _ in NEW if who in walkers or who in portraits}
    for who in portraits:
        looks.setdefault(who, {})['portrait'] = f'portrait_{who}'
    ts = '/* generated by tools/build_people.py — do not edit */\n\n'
    ts += '/** sprite bases with a walk cycle (npc_<who>_<dir>_<0-3>) */\n'
    ts += 'export const WALKERS: string[] = ' + json.dumps(sorted(set(walkers))) + ';\n\n'
    ts += '/** people with a look of their own now (they borrowed someone else\'s before) */\n'
    ts += 'export const PEOPLE_LOOKS: Record<string, { sprite?: string; portrait?: string }> = ' + json.dumps(looks, indent=1) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'people.gen.ts'), 'w').write(ts)
    print(len(walkers), 'walkers,', len(portraits), 'portrait sets')


if __name__ == '__main__':
    main()
