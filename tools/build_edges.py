"""
Closes the map borders where a painted road or path runs into the edge but there is no exit: without this you see a
way that goes on, walk there and nothing happens.

Along each edge, the runs of walkable path tiles that are reachable and are no exit get a visible barrier on the
outermost tile row: bollards across roads (asphalt), hedges elsewhere. The tiles next to exits and arrival points
stay open. Writes src/content/edges.gen.ts (decor objects per map), used by maps.ts.

Input: a JSON dump of the outdoor maps without these barriers (tiles as solid grid, exits, arrival points), made by
tools/dump_walk.mts:  npx vite-node tools/dump_walk.mts <out.json> && python3 tools/build_edges.py <out.json>
"""
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, 'public', 'assets')
T = 32


def classify(img, H, W):
    a = np.asarray(img).astype(float) / 255
    mx, mn = a.max(2), a.min(2)
    sat = np.where(mx > 0, (mx - mn) / np.maximum(mx, 1e-6), 0)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    green = (g > r * 1.05) & (g > b * 1.1) & (sat > .25)
    blue = (b > r * 1.25) & (b > g) & (sat > .3)
    path = (~green) & (~blue) & (((sat < .3) & (mx > .35)) | ((r > .55) & (g > .4) & (b > .25) & (r - b > .15) & (sat < .55)))
    road = (sat < .18) & (mx > .2) & (mx < .5)
    frac = lambda m: m[:H * T, :W * T].reshape(H, T, W, T).mean((1, 3))
    return frac(path) > .5, frac(road) > .5


def reach(walk, starts):
    H, W = walk.shape
    seen = np.zeros_like(walk)
    st = [(x, y) for x, y in starts if 0 <= y < H and 0 <= x < W and walk[y, x]]
    for x, y in st:
        seen[y, x] = True
    while st:
        x, y = st.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < W and 0 <= ny < H and walk[ny, nx] and not seen[ny, nx]:
                seen[ny, nx] = True
                st.append((nx, ny))
    return seen


def main():
    D = json.load(open(sys.argv[1]))
    out = {}
    for mid, m in D.items():
        sol = np.array(m['solid'])
        H, W = sol.shape
        img = Image.open(os.path.join(A, m['image'] + '.png')).convert('RGB').resize((W * T, H * T))
        path, road = classify(img, H, W)
        walk = sol == 0
        seen = reach(walk, m['entries'])
        keep = set()
        for x, y, _ in m['warps']:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    keep.add((x + dx, y + dy))
        for x, y in m['entries']:
            keep.add((x, y))
        dead = np.zeros_like(walk)
        for y in range(H):
            for x in range(W):
                if (x in (0, W - 1) or y in (0, H - 1)) and seen[y, x] and (path[y, x] or road[y, x]) and (x, y) not in keep:
                    dead[y, x] = True
        objs = []
        taken = set()

        def put(sprite, x, y, w=1, h=1):
            cells = [(x + i, y + j) for i in range(w) for j in range(h)]
            if any(c in taken or c in keep or not (0 <= c[0] < W and 0 <= c[1] < H) or not walk[c[1], c[0]] for c in cells):
                return False
            # never cut off an exit or arrival point
            trial = walk.copy()
            for cx, cy in cells:
                trial[cy, cx] = False
            after = reach(trial, m['entries'])
            for wx, wy, _ in m['warps']:
                if not any(0 <= wy + dy < H and 0 <= wx + dx < W and after[wy + dy, wx + dx] for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1))):
                    return False
            for c in cells:
                taken.add(c)
            for cx, cy in cells:
                walk[cy, cx] = False
            objs.append({'id': f'{mid}_edge{len(objs)}', 'sprite': sprite, 'x': x, 'y': y, 'w': w, 'h': h, 'solid': True, 'decor': True})
            return True

        for y in range(H):
            for x in range(W):
                if not dead[y, x] or (x, y) in taken:
                    continue
                horizontal = y in (0, H - 1)
                if road[y, x]:
                    put('ob_bollard', x, y)
                elif horizontal and x + 1 < W and dead[y, x + 1] and not road[y, x + 1]:
                    put('ob_hedge_h', x, y, 2, 1) or put('ob_hedge_block', x, y)
                elif not horizontal and y + 1 < H and dead[y + 1, x] and not road[y + 1, x]:
                    put('ob_hedge_v', x, y, 1, 2) or put('ob_hedge_block', x, y)
                else:
                    put('ob_hedge_block', x, y)
        out[mid] = objs
        print(mid.ljust(14), 'dead edge tiles', int(dead.sum()), 'barriers', len(objs))
    ts = '/* generated by tools/build_edges.py — do not edit */\nimport type { MapObject } from \'./maps\';\n\n'
    ts += '/** barriers on the map borders where a painted way runs into the edge without an exit */\n'
    ts += 'export const EDGES_GEN: Record<string, MapObject[]> = ' + json.dumps(out) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'edges.gen.ts'), 'w').write(ts)


if __name__ == '__main__':
    main()
