"""
Builds the sixteen new interiors (tools/rooms2_spec.py): shops in Kyoto, Osaka and Tokyo and the village halls.

  art/sheets/room_<id>.webp      the painted room (W x H tiles of 64 px, magenta outside)
  art/furniture/<id>/NN.png      its furniture, cut by tools/cut_new_furniture.py

Outputs:
  public/assets/room2_<id>.png   the room scaled to 32 px per tile
  public/assets/fu_<id>_<name>.png
  src/content/rooms2.gen.ts      tiles, objects, NPC definitions, doors
  src/content/scripts_rooms2.gen.ts  the interaction texts

Run: python3 tools/cut_new_furniture.py && python3 tools/build_new_rooms.py
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
import build_rooms as br  # noqa: E402
from extract_sheets import OUT, ROOT, resize_px  # noqa: E402
from rooms2_spec import NPCS, ROOMS, TEXT  # noqa: E402

T = br.T


def door_cols(W):
    return [W // 2 - 1, W // 2] if W % 2 == 0 else [W // 2 - 1, W // 2, W // 2 + 1]


def grid_for(W, H, doors):
    g = [['W'] * W for _ in range(3)]
    g.append(list('WW' + 'c' * (W - 4) + 'WW'))
    for _ in range(4, H - 1):
        g.append(list('WW' + 'f' * (W - 4) + 'WW'))
    g.append(['D' if x in doors else 'W' for x in range(W)])
    return g


def sprite(rid, name, no, tw):
    img = Image.open(os.path.join(ROOT, 'art', 'furniture', rid, f'{no:02d}.png')).convert('RGBA')
    h = max(8, round(img.height * tw * T / img.width))
    resize_px(img, h).save(os.path.join(OUT, f'fu_{rid}_{name}.png'))


def esc(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    out, scripts = {}, {}
    for rid, r in ROOMS.items():
        W, H = r['size']
        doors = door_cols(W)
        shell = dict(size=(W, H), painted=f'room_{rid}.webp', clean=True, crop=(0, 0, W * 64, H * 64), grid=grid_for(W, H, doors))
        grid = br.painted_shell(rid, shell)
        # the shell is saved as room2_<rid>.png; the shopkeeper's tile is floor (the test walks to NPCs), the counter in front blocks the way
        grid[r['npc'][2]][r['npc'][1]] = 'f'
        objects = []
        for name, no, x, y, w, h, tw, script in r['furniture']:
            sprite(rid, name, no, tw)
            o = {'id': f'{rid}_{name}', 'sprite': f'fu_{rid}_{name}', 'x': x, 'y': y, 'w': w, 'h': h}
            if script:
                o['script'] = script
            else:
                o['decor'] = True
            objects.append(o)
            if script:
                scripts[script] = [{'steps': [{'say': TEXT[script][0], 'en': TEXT[script][1]}]}]
        for name, x, y, w, h, script in r['spots']:
            objects.append({'id': f'{rid}_{name}', 'x': x, 'y': y, 'w': w, 'h': h, 'script': script})
            scripts[script] = [{'steps': [{'say': TEXT[script][0], 'en': TEXT[script][1]}]}]
        nid, nx, ny, nface = r['npc']
        scripts[nid] = [{'steps': [{'say': jp, 'who': nid, 'en': en} for jp, en in TEXT[nid]]}]
        emap, etiles, (sx, sy, sface) = r['ext']
        out[rid] = {
            'name': r['name'], 'nameJa': r['nameJa'], 'image': f'room2_{rid}', 'tiles': [''.join(row) for row in grid], 'objects': objects,
            'npc': {'id': nid, 'x': nx, 'y': ny, 'facing': nface}, 'doors': doors, 'size': [W, H],
            'ext': {'map': emap, 'tiles': [list(t) for t in etiles], 'stand': {'x': sx, 'y': sy, 'facing': sface}},
        }
    npcs = {k: {'id': k, 'name': v[0], 'nameEn': v[1], 'role': v[1], 'sprite': f'npc_{v[2]}', 'portrait': f'portrait_{v[2]}', 'color': v[3]} for k, v in NPCS.items()}
    ts = '/* generated by tools/build_new_rooms.py — do not edit */\n'
    ts += "import type { MapObject } from './maps';\nimport type { NpcDef } from './npcs';\n\n"
    ts += 'export interface Room2 {\n  name: string;\n  nameJa: string;\n  image: string;\n  tiles: string[];\n  objects: MapObject[];\n'
    ts += "  npc: { id: string; x: number; y: number; facing: 'up' | 'down' | 'left' | 'right' };\n  doors: number[];\n  size: [number, number];\n"
    ts += "  ext: { map: string; tiles: [number, number][]; stand: { x: number; y: number; facing: 'up' | 'down' | 'left' | 'right' } };\n}\n\n"
    ts += 'export const ROOMS2_GEN: Record<string, Room2> = ' + json.dumps(out, ensure_ascii=False, indent=1) + ' as Record<string, Room2>;\n\n'
    ts += 'export const ROOMS2_NPCS: Record<string, NpcDef> = ' + json.dumps(npcs, ensure_ascii=False, indent=1) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'rooms2.gen.ts'), 'w').write(ts)
    st = '/* generated by tools/build_new_rooms.py — do not edit */\nimport type { DialogueRule } from \'../core/script\';\n\n'
    st += 'export const ROOMS2_SCRIPTS: Record<string, DialogueRule[]> = ' + json.dumps(scripts, ensure_ascii=False, indent=1) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'scripts_rooms2.gen.ts'), 'w').write(st)
    print('rooms:', len(out), 'scripts:', len(scripts))


if __name__ == '__main__':
    main()
