"""
Closes the outermost tile ring of the outdoor maps where the repainted ground (the Klarheit images) shows a wall,
rim or planting there: without this you could walk on the painted border. Ring tiles next to exits and arrival
points stay open, tiles where the picture still shows a way are left to tools/build_edges.py (a visible barrier),
and a tile is only closed when every exit stays reachable. Writes src/content/border.gen.ts, used by maps.ts.

  npx vite-node tools/dump_walk.mts <walk.json> raw   (raw: without these border tiles)
  python3 tools/build_border.py <walk.json>
"""
import json
import os
import sys

import numpy as np
from PIL import Image

from build_edges import A, ROOT, T, classify, reach


def main():
    D = json.load(open(sys.argv[1]))
    out = {}
    for mid, m in D.items():
        sol = np.array(m['solid'])
        H, W = sol.shape
        img = Image.open(os.path.join(A, m['image'] + '.png')).convert('RGB').resize((W * T, H * T))
        path, road = classify(img, H, W)
        walk = sol == 0
        keep = {(x, y) for x, y in m['entries']}
        for x, y, _ in m['warps']:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    keep.add((x + dx, y + dy))
        closed = []
        for y in range(H):
            for x in range(W):
                if not (x in (0, W - 1) or y in (0, H - 1)) or not walk[y, x] or (x, y) in keep or path[y, x] or road[y, x]:
                    continue
                walk[y, x] = False
                after = reach(walk, m['entries'])
                ok = all(any(0 <= wy + dy < H and 0 <= wx + dx < W and after[wy + dy, wx + dx] for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1))) for wx, wy, _ in m['warps'])
                if ok:
                    closed.append([x, y])
                else:
                    walk[y, x] = True
        out[mid] = closed
        print(mid.ljust(14), 'border tiles closed', len(closed))
    ts = '/* generated by tools/build_border.py — do not edit */\n\n'
    ts += '/** outermost tiles that the repainted ground shows as wall, rim or planting: not walkable */\n'
    ts += 'export const BORDER_GEN: Record<string, [number, number][]> = ' + json.dumps(out, separators=(',', ':')) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'border.gen.ts'), 'w').write(ts)


if __name__ == '__main__':
    main()
