"""
Hinomori valley (chapter 2) from the painted ground (art/sheets/ground_valley_draft.webp, 42 x 28 tiles).

Writes:
  public/assets/map_valley.png     the ground picture scaled to the grid
  public/assets/bx_<name>.png      valley buildings (hm_exterior_valley.webp, bx_ryokan.webp)
  src/content/valley.gen.ts        collision / terrain grid

The grid was read off the picture by hand: everything is blocked (forest, cliffs) unless carved out.
Legend: . walkable  " tall grass (wild Kotodama)  ~ water  b bridge  H stairs  T blocked

Run: python3 tools/build_valley.py
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from build_rooms import piece, sheet, strict_bg  # noqa: E402
from extract_sheets import OUT, ROOT, load, resize_px, to_rgba, trim  # noqa: E402
from scipy import ndimage  # noqa: E402

W, H, T = 42, 28, 32
g = [['T'] * W for _ in range(H)]


def rect(ch, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


# --- north bank: farm plot, vineyard paths, peach grove
rect('.', 2, 2, 11, 7)          # farm plot with its grass border
rect('H', 8, 7, 9, 7)           # stairs down from the farm
rect('.', 12, 1, 13, 7)         # path west of the vineyard
rect('.', 18, 1, 19, 8)         # path between the vineyards
rect('.', 24, 1, 24, 6)         # path east of the vineyard
rect('"', 25, 1, 32, 4)         # peach grove (tall grass)
rect('.', 8, 8, 18, 8)          # path along the north bank
rect('.', 11, 9, 15, 9)
# --- bridge and river
rect('~', 20, 6, 33, 9)         # upper river
rect('~', 34, 0, 39, 8)         # hot-spring falls
rect('~', 9, 10, 17, 13)        # river under the bridge, flowing west
rect('~', 1, 14, 9, 21)         # lower river and falls
rect('b', 16, 9, 17, 10)
rect('b', 18, 10, 19, 11)
# --- west peninsula between the river arms
rect('.', 10, 11, 12, 13)
rect('H', 11, 10, 11, 10)
rect('.', 6, 12, 9, 13)
rect('H', 5, 14, 5, 14)
rect('"', 2, 15, 7, 17)
# --- village centre
rect('.', 20, 11, 21, 27)       # main road down to the bus road
rect('.', 22, 11, 27, 12)       # road east along the river
rect('.', 28, 10, 33, 11)
rect('H', 34, 10, 34, 11)
rect('.', 35, 9, 40, 11)        # footbath and onsen square
rect('.', 14, 13, 26, 21)       # square, plots and lawns
rect('T', 19, 17, 21, 18)       # the big tree in the middle of the square
rect('.', 25, 16, 28, 17)       # path to the inn
rect('.', 28, 12, 38, 17)       # inn plot
rect('.', 27, 17, 28, 22)       # path down to the paddies
rect('.', 22, 21, 27, 21)
rect('~', 29, 19, 40, 24)       # rice paddies
rect('.', 34, 19, 34, 22)       # walkway between the paddies
# --- bus road leaves the map at the bottom
rect('.', 19, 22, 21, 27)

# buildings: name -> (sheet, index or None, width px, footprint x, y, w, h)
BUILDINGS = {
    'farmhouse': ('exterior_valley', 1, 176, 4, 4, 5, 2),
    'winery': ('exterior_valley', 2, 140, 22, 13, 4, 2),
    'stand': ('exterior_valley', 3, 104, 15, 19, 3, 1),
    'workshop': ('exterior_valley', 4, 116, 16, 14, 3, 1),
    'busstop': ('exterior_valley', 5, 104, 22, 19, 3, 1),
    'ryokan': (None, None, 232, 29, 13, 7, 2),
}


def cut_single(name, width):
    a = load(name)
    m = ndimage.binary_opening(~strict_bg(a), iterations=1)
    img = trim(to_rgba(a, m))
    return resize_px(img, round(img.height * width / img.width))


def main():
    sheet('exterior_valley')
    for key, (sh, idx, width, x, y, w, h) in BUILDINGS.items():
        img = cut_single('bx_ryokan.webp', width) if sh is None else piece(sh, idx, scale=1)
        if sh is not None:
            img = resize_px(img, round(img.height * width / img.width))
        img.save(os.path.join(OUT, f'bx_{key}.png'))
        rect('T', x, y, x + w - 1, y + h - 1)  # buildings block
    rows = [''.join(r) for r in g]
    src = Image.open(os.path.join(ROOT, 'art', 'sheets', 'ground_valley_draft.webp')).convert('RGB')
    src.resize((W * T, H * T), Image.LANCZOS).save(os.path.join(OUT, 'map_valley.png'))
    ts = '/* generated by tools/build_valley.py — do not edit */\nexport const VALLEY_GEN: string[] = ' + json.dumps(rows, indent=2) + ';\n'
    open(os.path.join(ROOT, 'src', 'content', 'valley.gen.ts'), 'w').write(ts)
    print('\n'.join(rows))


if __name__ == '__main__':
    main()
