"""
Hinomori valley (chapter 2) from the painted ground (art/sheets/ground_valley_draft.webp, 42 x 28 tiles).

Writes:
  public/assets/map_valley.png     the ground picture scaled to the grid
  public/assets/bx_<name>.png      valley buildings (hm_exterior_valley.webp, bx_ryokan.webp)
  src/content/valley.gen.ts        collision / terrain grid

The grid was read off the picture by hand: everything is blocked (forest, cliffs) unless carved out.
Legend: . walkable  " tall grass (wild Kotodama)  ~ water  b bridge  H stairs  T blocked

Run: python3 tools/build_valley.py
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from build_rooms import piece, sheet, strict_bg  # noqa: E402
from extract_sheets import OUT, ROOT, load, resize_px, to_rgba, trim  # noqa: E402
from scipy import ndimage  # noqa: E402

W, H, T = 42, 28, 32
g = [['T'] * W for _ in range(H)]


def rect(ch, x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = ch


# re-read from the painted ground on a 40 px grid (the first grid was drawn for an older draft)
# --- north bank: farm plot, vineyard paths, peach grove
rect('.', 2, 2, 11, 6)          # farm plot with its grass border
